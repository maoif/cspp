"""Regenerate rich's locale-independent terminal widths from Unicode 17.0.0.

Run manually with Python 3; normal builds use the checked-in Scheme tables.
Unicode data license: https://www.unicode.org/license.txt (Unicode-3.0).
"""
from pathlib import Path
from urllib.request import urlopen

VERSION = "17.0.0"
BASE = f"https://www.unicode.org/Public/{VERSION}/ucd/"
DEST = Path(__file__).resolve().parents[1] / "src/cspp/rich/private/cell-data.ss"


def properties(path, names):
    result = set()
    with urlopen(BASE + path, timeout=30) as response:
        for line in response.read().decode().splitlines():
            fields = line.split("#", 1)[0].strip().split(";")
            if len(fields) < 2 or fields[1].strip() not in names:
                continue
            bounds = fields[0].strip().split()[0].split("..")
            result.update(range(int(bounds[0], 16), int(bounds[-1], 16) + 1))
    return result


def intervals(points):
    result = []
    for point in sorted(points):
        if result and result[-1][1] + 1 == point:
            result[-1][1] = point
        else:
            result.append([point, point])
    return result


def main():
    # Chez already supplies categories, grapheme breaks and pictographic properties.
    tables = {
        "wide": properties("EastAsianWidth.txt", {"W", "F"}),
        "emoji": properties("emoji/emoji-variation-sequences.txt", {"emoji style"}),
    }
    with urlopen("https://www.unicode.org/license.txt", timeout=30) as response:
        license_text = response.read().decode().strip()
    lines = ["#!chezscheme", ";; Generated by tools/generate-rich-cell-data.py; do not edit.",
             f";; Unicode {VERSION}: EastAsianWidth and emoji-variation-sequences."]
    lines += [(";; " + line).rstrip() for line in license_text.splitlines()]
    lines += ["(library (cspp rich private cell-data)",
              "  (export rich-wide-ranges rich-emoji-ranges)", "  (import (cspp chez))"]
    for name, points in tables.items():
        lines += ["", f"  ;; Sorted inclusive {name} code point intervals.",
                  f"  (define rich-{name}-ranges", "    '#("]
        lines += [f"       #x{start:x} #x{end:x}" for start, end in intervals(points)]
        lines += ["       ))"]
    lines += [")", ""]
    DEST.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
